    private void btnSelectBookFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelectBookFileActionPerformed
javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
    int result = chooser.showOpenDialog(this);

    if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File selectedFile = chooser.getSelectedFile();
        
        // 1. Create a permanent storage folder on your C: drive
        java.io.File storageDir = new java.io.File("C:\\LibraryFiles");
        if (!storageDir.exists()) storageDir.mkdirs();

        // 2. Define the new path in the permanent folder
        java.io.File permanentFile = new java.io.File(storageDir, selectedFile.getName());

        try {
            // 3. COPY the file from your Desktop to C:\LibraryFiles
            java.nio.file.Files.copy(selectedFile.toPath(), permanentFile.toPath(), 
                                     java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            
            // 4. Update your text field to use the PERMANENT path
            // This is what gets saved to MySQL
            txtFilePath.setText(permanentFile.getAbsolutePath()); 
            
            javax.swing.JOptionPane.showMessageDialog(this, "File successfully stored in System!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Storage Error: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnSelectBookFileActionPerformed

