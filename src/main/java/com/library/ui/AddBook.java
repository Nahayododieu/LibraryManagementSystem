    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        
  String bookId = txtBookID.getText();
    String title = txtTitle.getText();
    String author = txtAuthor.getText();
    String category = cmbCategory.getSelectedItem().toString();
    int quantity = (Integer) spnQuantity.getValue();
    
    // NEW: Get the file path from the text field we created earlier
    String filePath = txtFilePath.getText(); 

    // Simple validation
    if (bookId.isEmpty() || title.isEmpty() || author.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all required fields");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        // UPDATED: Added file_path to the INSERT statement
        String sql = "INSERT INTO books (book_id, title, author, category, quantity, file_path) " +
                     "VALUES (?, ?, ?, ?, ?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, bookId);
        pst.setString(2, title);
        pst.setString(3, author);
        pst.setString(4, category);
        pst.setInt(5, quantity);
        
        // NEW: Set the file path in the 6th position
        pst.setString(6, filePath); 

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Book and Digital File saved successfully!");

        // Optional: Clear fields after saving
        txtBookID.setText("");
        txtTitle.setText("");
        txtFilePath.setText("");

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error saving book: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSaveActionPerformed

