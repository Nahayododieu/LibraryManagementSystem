    private void btnIssueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIssueActionPerformed
String bookID = txtBookID.getText();
    String studentID = txtStudentID.getText();
    String dueDate = txtDueDate.getText(); 
    
    // AUTOMATIC DATE LOGIC
    java.util.Date d = new java.util.Date();
    java.text.SimpleDateFormat s = new java.text.SimpleDateFormat("yyyy-MM-dd");
    String issueDate = s.format(d); // This will automatically be "2025-12-22" today
    
    String returnStatus = "No";

    try {
        java.sql.Connection con = com.library.database.DBConnection.getConnection();
        java.sql.Statement st = con.createStatement();
        
        // Correct way to format the SQL string
st.executeUpdate("insert into issue values('"+bookID+"', '"+studentID+"', '"+issueDate+"', '"+dueDate+"', 'No')");
        
        javax.swing.JOptionPane.showMessageDialog(null, "Book successfully issued on " + issueDate);
        this.setVisible(false);
        new IssueBook().setVisible(true);
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(null, "Error: Book already issued or ID invalid.");
    }
    }//GEN-LAST:event_btnIssueActionPerformed

