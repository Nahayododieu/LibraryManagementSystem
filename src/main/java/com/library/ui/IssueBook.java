    private void btnBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBookActionPerformed
try {
        Connection con = DBConnection.getConnection();
        Statement st = con.createStatement();
        // Search the 'books' table using 'book_id'
        ResultSet rs = st.executeQuery("SELECT * FROM books WHERE book_id='" + txtBookID.getText() + "'");
        
        if (rs.next()) {
            // Use "title" because that is what your database image shows
            jLabelBookName.setText("Book Found: " + rs.getString("title")); 
        } else {
            jLabelBookName.setText("Book not found");
            JOptionPane.showMessageDialog(null, "Incorrect Book ID");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnBookActionPerformed

