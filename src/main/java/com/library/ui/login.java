    private void btnloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloginActionPerformed
     // STEP 2: Fixed variable names to match the components (textuser and txtpass)
   // STEP 2: Fixed variable names to match the components (textuser and txtpass)
        String user = textuser.getText().trim();
        String pass = new String(txtpass.getPassword()); 

        if (user.isEmpty() || pass.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both Username and Password");
            return;
        }

        try {
            Connection con = DBConnection.getConnection();
            String sql = "SELECT * FROM users WHERE username=? AND password=?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, user);
            pst.setString(2, pass);
            
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Login Successful!");
                new Dashboard().setVisible(true);
                this.dispose(); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Invalid Username or Password");
                textuser.setText("admin");
                txtpass.setText("1234");
                textuser.requestFocus();
            }
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            logger.log(Level.SEVERE, null, e);
        }
    
    }//GEN-LAST:event_btnloginActionPerformed

