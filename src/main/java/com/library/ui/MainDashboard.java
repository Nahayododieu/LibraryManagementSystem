    public void updateBackgroundImage() {
    try {
        // 1. Load the original image
        ImageIcon icon = new ImageIcon(getClass().getResource("/images/photo.jpg"));
        Image img = icon.getImage();
        
        // 2. Get the current size of the label
        // If the label is 0 (not drawn yet), we use a default small size
        int width = lblBackground.getWidth() > 0 ? lblBackground.getWidth() : 30;
        int height = lblBackground.getHeight() > 0 ? lblBackground.getHeight() : 20;
        
        // 3. Force the image to "minimize" to the label's size
        Image scaledImg = img.getScaledInstance(width, height, Image.SCALE_SMOOTH);
        
        // 4. Set the new small image to the label
        lblBackground.setIcon(new ImageIcon(scaledImg));
        
    } catch (Exception e) {
        System.out.println("Could not minimize image: " + e.getMessage());
    }
}

