    private void btncreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncreateActionPerformed
    // 2. FIXED VARIABLE NAMES (Changed txtUser to txtuser to match your design)
        String user = txtuser.getText().trim();
        String pass = new String(txtpass.getPassword());
        String confirmPass = new String(txtconfirmpass.getPassword());

        if (user.isEmpty() || pass.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "All fields are required!");
            return;
        }

        if (!pass.equals(confirmPass)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Passwords do not match!");
            return;
        }

        try {
            Connection con = DBConnection.getConnection();
            String sql = "INSERT INTO users (username, password) VALUES (?, ?)";
            PreparedStatement pst = con.prepareStatement(sql);
            
            pst.setString(1, user);
            pst.setString(2, pass);
            
            pst.executeUpdate();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Account Created Successfully!");
            
            // Clear fields
            txtuser.setText("");
            txtpass.setText("");
            txtconfirmpass.setText("");
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Username might already exist.");
            logger.log(Level.SEVERE, null, e);
        }
 
    }//GEN-LAST:event_btncreateActionPerformed

