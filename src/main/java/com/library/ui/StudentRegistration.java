    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
   try {
        // 1. Capture data from UI
        String id = txtStudentID.getText().trim();
        String name = txtName.getText().trim();
        String mobile = txtMobile.getText().trim();
        String email = txtEmail.getText().trim();
        String gender = cmbGender.getSelectedItem().toString();
        String studentClass = cmbClass.getSelectedItem().toString();
        String department = cmbDepartment.getSelectedItem().toString();
        String semester = cmbSemester.getSelectedItem().toString();
        String address = txtaddress.getText().trim(); // Use the JTextArea name

        // 2. Validation
        if (id.isEmpty() || name.isEmpty() || id.equals("StudentID")) {
            JOptionPane.showMessageDialog(this, "Please enter a valid Student ID and Name.");
            return;
        }

        // 3. Database Operation
        Connection con = DBConnection.getConnection();
        
        // Ensure the column order matches your MySQL table exactly
        String sql = "INSERT INTO students (student_id, name, gender, department, mobile, email, address, semester, student_class) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";
        
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, Integer.parseInt(id));
        pst.setString(2, name);
        pst.setString(3, gender);
        pst.setString(4, department);
        pst.setString(5, mobile);
        pst.setString(6, email);
        pst.setString(7, address);
        pst.setString(8, semester);
        pst.setString(9, studentClass);

        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "Student Registered Successfully!");
        
        // Clear fields after success
        btnResetActionPerformed(null);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Student ID must be a number!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnSaveActionPerformed

