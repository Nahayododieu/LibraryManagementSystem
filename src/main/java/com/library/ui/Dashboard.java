   public void updateStatistics() {
    try {
        Connection con = DBConnection.getConnection();
        Statement st = con.createStatement();
        
        // 1. Get Total Books
        ResultSet rsTotal = st.executeQuery("SELECT COUNT(*) FROM books");
        int total = 0;
        if (rsTotal.next()) {
            total = rsTotal.getInt(1);
        }
        
        // 2. Get Issued Books (Not yet returned)
        ResultSet rsIssued = st.executeQuery("SELECT COUNT(*) FROM issue WHERE return_status='No'");
        int issued = 0;
        if (rsIssued.next()) {
            issued = rsIssued.getInt(1);
        }
        
        // 3. Calculate Available
        int available = total - issued;
        
        // 4. Update the Labels on the Dashboard
        lblTotalBooks.setText(String.valueOf(total));
        lblIssuedCount.setText(String.valueOf(issued));
        lblAvailable.setText(String.valueOf(available));
        
    } catch (Exception e) {
        System.out.println("Error updating stats: " + e.getMessage());
    }
}

