    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        String userToDelete = txtDeleteUser.getText().trim();

    // 1. Validation: Don't allow empty input
    if (userToDelete.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a username to delete.");
        return;
    }

    // 2. Safety Check: Ask "Are you sure?"
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete user: " + userToDelete + "?", 
            "Confirm Deletion", javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        try {
            Connection con = DBConnection.getConnection();
            
            // SQL query to delete the user
            String sql = "DELETE FROM users WHERE username = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, userToDelete);

            int rowsDeleted = pst.executeUpdate();

            if (rowsDeleted > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "User deleted successfully!");
                txtDeleteUser.setText(""); // Clear the field
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "User not found.");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

