    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        // 1. Get the selected row index from the table
    int selectedRow = tblBooks.getSelectedRow();
    
    // 2. Check if a row is actually selected
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a book from the table to delete.");
        return;
    }

    // 3. Get the Book ID from the first column (index 0) of the selected row
    String bookID = tblBooks.getValueAt(selectedRow, 0).toString();

    // 4. Confirm the deletion with the user
    int response = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete Book ID: " + bookID + "?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);

    if (response == JOptionPane.YES_OPTION) {
        try {
            Connection con = DBConnection.getConnection();
            Statement st = con.createStatement();
            
            // 5. Execute the delete query
            String query = "DELETE FROM books WHERE book_id = '" + bookID + "'";
            int result = st.executeUpdate(query);

            if (result > 0) {
                JOptionPane.showMessageDialog(this, "Book deleted successfully!");
                // 6. Refresh the table to show the book is gone
                showAllBooks(); 
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnDownloadBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDownloadBookActionPerformed
int row = tblBooks.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a book from the table!");
        return;
    }

    // Index 4 is your 'File_Path' column based on your screenshot
    Object pathObj = tblBooks.getValueAt(row, 4);
    
    // FIX: Check if the path is empty in the table first
    if (pathObj == null || pathObj.toString().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "This book does not have a digital file attached.\nPlease contact the Admin.");
        return;
    }

    java.io.File sourceFile = new java.io.File(pathObj.toString());

    // Check if the file actually exists at that path
    if (!sourceFile.exists()) {
        JOptionPane.showMessageDialog(this, "Error: The file has been moved or deleted from:\n" + pathObj.toString());
        return;
    }

    try {
        String home = System.getProperty("user.home");
        java.io.File targetFile = new java.io.File(home + java.io.File.separator + "Downloads" + java.io.File.separator + sourceFile.getName());

        // Use the robust copy method to prevent corruption
        java.nio.file.Files.copy(sourceFile.toPath(), targetFile.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING);

        JOptionPane.showMessageDialog(this, "Download Complete!\nSaved to your Downloads folder.");
        
        // Open the file automatically
        java.awt.Desktop.getDesktop().open(targetFile);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Technical Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnDownloadBookActionPerformed

    private void txtSearchTitleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSearchTitleActionPerformed
String searchTitle = txtSearchTitle.getText().trim();
    DefaultTableModel model = (DefaultTableModel) tblBooks.getModel();
    model.setRowCount(0); 

    try {
        Connection con = DBConnection.getConnection();
        // Use PreparedStatement for safety
        String query = "SELECT * FROM books WHERE title LIKE ?"; 
        PreparedStatement pst = con.prepareStatement(query);
        pst.setString(1, "%" + searchTitle + "%");
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            String id = rs.getString("book_id");
            String title = rs.getString("title");
            String author = rs.getString("author");
            String qty = rs.getString("quantity");
            // YOU MUST FETCH THE PATH HERE
            String path = rs.getString("file_path");

            // YOU MUST ADD ALL 5 ITEMS
            model.addRow(new Object[]{id, title, author, qty, path});
        }
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Search Error: " + e.getMessage());
    }

    }//GEN-LAST:event_txtSearchTitleActionPerformed

