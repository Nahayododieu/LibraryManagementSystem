    public void loadHistoryData() {
        DefaultTableModel model = (DefaultTableModel) tblHistory.getModel();
        model.setRowCount(0); // Clear existing data

        try {
            Connection con = DBConnection.getConnection();
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT * FROM returnbooks");

      while (rs.next()) {
    // rs.getString("column_name") gets the ACTUAL date from the database
    String bID = rs.getString(1); // Book ID
    String sID = rs.getString(2); // Student ID
    String iDate = rs.getString(3); // This gets the actual date value
    String dDate = rs.getString(4); // This gets the actual date value
    String rDate = rs.getString(5); // Return Date

    model.addRow(new Object[]{bID, sID, iDate, dDate, rDate});
}
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error loading history: " + e.getMessage());
        }
    }

