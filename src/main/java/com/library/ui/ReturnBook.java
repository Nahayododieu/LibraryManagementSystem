    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
try {
        Connection con = DBConnection.getConnection();
        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery("select * from issue where book_id='"+txtBookID.getText()+"' and student_id='"+txtStudentID.getText()+"' and return_status='No'");
        
        // PASTE THIS PART HERE:
        if(rs.next()) {
            txtIssue.setText(rs.getString("issue_date")); 
            txtDue.setText(rs.getString("due_date")); 
        } else {
            JOptionPane.showMessageDialog(null, "No record found or Book already returned.");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Connection Error");
    }

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnReturnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReturnActionPerformed
 // 1. Get data from the fields
    String bookID = txtBookID.getText();
    String studentID = txtStudentID.getText();

    // PASTE THESE TWO LINES HERE:
    String issueDate = txtIssue.getText(); 
    String dueDate = txtDue.getText();
    
    String returnDate = "2025-12-22"; 

    try {
        Connection con = DBConnection.getConnection();
        Statement st = con.createStatement();
        
        // Use the returnbooks table you created
        st.executeUpdate("INSERT INTO returnbooks VALUES('" + bookID + "', '" + studentID + "', '" + issueDate + "', '" + dueDate + "', '" + returnDate + "')");
        st.executeUpdate("DELETE FROM issue WHERE book_id='" + bookID + "' AND student_id='" + studentID + "'");
        
        JOptionPane.showMessageDialog(null, "Book Successfully Returned!");
        this.dispose();
        new ReturnBook().setVisible(true);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnReturnActionPerformed

